"""Align document keys with the integer models without deleting rows.

Run from backend: .venv/Scripts/python scripts/migrate_document_integer_ids.py
Legacy nonnumeric IDs require an explicit data migration and are rejected.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy import inspect, text

from database.connection import engine


def migrate():
    with engine.begin() as connection:
        if connection.dialect.name != "postgresql":
            raise RuntimeError("This migration requires PostgreSQL.")
        connection.execute(text("SELECT pg_advisory_xact_lock(742901663)"))
        connection.execute(text("SET LOCAL lock_timeout = '5s'"))
        connection.execute(text("LOCK TABLE documents, document_chat_turns IN ACCESS EXCLUSIVE MODE"))
        for table, column in (("documents", "id"), ("document_chat_turns", "document_id")):
            invalid = connection.scalar(text(
                f"SELECT count(*) FROM {table} WHERE {column}::text !~ '^[0-9]+$'"
            ))
            if invalid:
                raise RuntimeError("Nonnumeric legacy document IDs exist; no changes were applied.")

        inspector = inspect(connection)
        foreign_keys = [fk for fk in inspector.get_foreign_keys("document_chat_turns")
                        if fk["referred_table"] == "documents" and fk["constrained_columns"] == ["document_id"]]
        quote = connection.dialect.identifier_preparer.quote
        for fk in foreign_keys:
            connection.execute(text(f"ALTER TABLE document_chat_turns DROP CONSTRAINT {quote(fk['name'])}"))
        connection.execute(text("ALTER TABLE documents ALTER COLUMN id TYPE INTEGER USING id::integer"))
        connection.execute(text(
            "ALTER TABLE document_chat_turns ALTER COLUMN document_id TYPE INTEGER USING document_id::integer"
        ))
        column = next(col for col in inspect(connection).get_columns("documents") if col["name"] == "id")
        if not column.get("identity") and column.get("default") is None:
            connection.execute(text("ALTER TABLE documents ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY"))
        connection.execute(text(
            "SELECT setval(pg_get_serial_sequence('documents', 'id'), "
            "GREATEST(COALESCE(MAX(id), 0) + 1, 1), false) FROM documents"
        ))
        connection.execute(text(
            "ALTER TABLE document_chat_turns ADD CONSTRAINT fk_document_chat_turns_document "
            "FOREIGN KEY (document_id) REFERENCES documents(id)"
        ))
    print("Document integer keys and automatic ID generation are configured.")


if __name__ == "__main__":
    migrate()
