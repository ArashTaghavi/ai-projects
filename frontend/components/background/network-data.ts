const meshNodes = Array.from({ length: 12 }, (_, row) =>
    Array.from({ length: 18 }, (_, column) => [
        30 + column * 81 + Math.sin(row * 7 + column * 3) * 22,
        28 + row * 76 + Math.cos(column * 5 + row * 2) * 18,
    ]),
);

const meshPaths = [
    ...meshNodes.map((row) => `M${row.map(([x, y]) => `${x} ${y}`).join(" ")}`),
    ...Array.from(
        { length: 17 },
        (_, column) =>
            `M${meshNodes.map((row, index) => row[column + (index % 2)].join(" ")).join(" ")}`,
    ),
];

